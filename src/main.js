function pieceCard(piece) {
  const slides = piece.images.map((img, i) => `
    <img
      class="piece-slide${i === 0 ? ' is-active' : ''}"
      src="${img.src}"
      alt="${img.alt}"
      title="${img.title}"
      loading="lazy"
      data-index="${i}"
    >
  `).join('');

  const dots = piece.images.length > 1
    ? `<div class="piece-dots" role="tablist" aria-label="Фотографии экспоната">
        ${piece.images.map((_, i) => `
          <button
            type="button"
            class="piece-dot${i === 0 ? ' is-active' : ''}"
            data-index="${i}"
            aria-label="Фото ${i + 1}"
          ></button>
        `).join('')}
      </div>`
    : '';

  const arrows = piece.images.length > 1
    ? `<button type="button" class="piece-arrow piece-arrow-prev" aria-label="Предыдущее фото">‹</button>
       <button type="button" class="piece-arrow piece-arrow-next" aria-label="Следующее фото">›</button>`
    : '';

  return `
    <article class="piece-card" data-piece>
      <div class="piece-image" aria-label="${piece.title}">
        <div class="piece-slider">
          ${slides}
        </div>
        ${arrows}
        ${dots}
        <span class="piece-number">${piece.number}</span>
      </div>
      <div class="piece-info">
        <span class="eyebrow">${piece.era}</span>
        <h3>${piece.title}</h3>
        <div class="piece-description" data-collapsible>
          <div class="piece-description-inner">
            ${(Array.isArray(piece.description) ? piece.description : piece.description.split('\n')).map(line => `<p>${line}</p>`).join('')}
          </div>
        </div>
        <button type="button" class="piece-more" data-more hidden>
          Читать далее <span>↓</span>
        </button>
      </div>
    </article>
  `;
}

