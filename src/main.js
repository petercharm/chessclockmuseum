document.querySelectorAll('[data-piece]').forEach(card => {
  const slides = card.querySelectorAll('.piece-slide');
  const dots = card.querySelectorAll('.piece-dot');
  if (slides.length <= 1) return;

  let current = 0;

  const show = index => {
    current = (index + slides.length) % slides.length;
    slides.forEach((s, i) => s.classList.toggle('is-active', i === current));
    dots.forEach((d, i) => d.classList.toggle('is-active', i === current));
  };

  card.querySelector('.piece-arrow-prev')?.addEventListener('click', () => show(current - 1));
  card.querySelector('.piece-arrow-next')?.addEventListener('click', () => show(current + 1));
  dots.forEach(dot => {
    dot.addEventListener('click', () => show(Number(dot.dataset.index)));
  });
});

document.querySelectorAll('[data-collapsible]').forEach(box => {
  const moreBtn = box.parentElement.querySelector('[data-more]');
  if (!moreBtn) return;

  const inner = box.querySelector('.piece-description-inner');

  const update = () => {
    // Показываем кнопку, только если текст не влезает в свёрнутую высоту
    const collapsedMax = parseFloat(getComputedStyle(box).maxHeight);
    const needsMore = inner.scrollHeight > collapsedMax + 1;

    box.classList.add('is-collapsed');

    if (needsMore) {
      moreBtn.hidden = false;
    } else {
      moreBtn.hidden = true;
      box.classList.remove('is-collapsed');
    }
  };

  update();

  moreBtn.addEventListener('click', () => {
    const expanded = box.classList.toggle('is-expanded');
    box.classList.toggle('is-collapsed', !expanded);
    moreBtn.firstChild.textContent = expanded ? 'Свернуть ' : 'Читать далее ';
    moreBtn.setAttribute('aria-expanded', String(expanded));
  });

  // Пересчёт при ресайзе — вдруг на широком экране текст уже влезает
  window.addEventListener('resize', () => {
    if (box.classList.contains('is-expanded')) return;
    update();
  });
});
